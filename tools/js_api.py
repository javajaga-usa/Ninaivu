"""Write ninaivu/static/js/api.js: one JavaScript function per API route.

The functions are made from the route manifest (tests/data/route_manifest.txt,
which tools/route_manifest.py writes and tests/test_route_manifest.py keeps
current), so the browser's list of what it may ask the server is the server's
own list, not a second copy typed by hand.

Two exports, one per face: ``home`` holds the family app's routes and
``admin`` the console's. Each function is named for its method and its path:

    GET  /api/admin/overview            ->  admin.getAdminOverview(options)
    POST /api/assets/<int:asset_id>/rotate
                                        ->  home.postAssetsByAssetIdRotate(assetId, options)

``options`` is ``{ query, body, signal }``. The family app's functions go
through the same fetch layer as the rest of the family app (http.js: one
question per URL at a time, the sign-in screen on a lost session); the
console's through the console's own (``consoleJson``).

    python tools/js_api.py          # write it
    python tools/js_api.py --check  # exit 1 if it is out of date
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "tests" / "data" / "route_manifest.txt"
FILE = ROOT / "ninaivu" / "static" / "js" / "api.js"

_PARAM = re.compile(r"^<(?:(\w+):)?(\w+)>$")


def _words(text: str) -> list[str]:
    return [w for w in re.split(r"[^A-Za-z0-9]+", text) if w]


def _camel(words: list[str]) -> str:
    return words[0].lower() + "".join(w[:1].upper() + w[1:] for w in words[1:]) if words else ""


def _pascal(words: list[str]) -> str:
    return "".join(w[:1].upper() + w[1:] for w in words)


def parse(text: str) -> list[tuple[str, str, str]]:
    """(face, method, rule) for every /api/ route in the manifest's text."""
    found = []
    for line in text.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        face, methods, rule, *_ = (part.strip() for part in line.split("|"))
        if not rule.startswith("/api/"):
            continue
        for method in methods.split(","):
            if method not in ("HEAD", "OPTIONS"):
                found.append((face, method, rule))
    return found


def function(method: str, rule: str) -> tuple[str, str]:
    """The function's name and its one line of JavaScript."""
    name_parts: list[str] = []
    params: list[str] = []
    pieces: list[str] = []
    for segment in rule.removeprefix("/api/").split("/"):
        match = _PARAM.match(segment)
        if match:
            converter, param = match.groups()
            arg = _camel(_words(param))
            params.append(arg)
            name_parts += ["By"] + [w[:1].upper() + w[1:] for w in _words(param)]
            pieces.append("${" + ("path" if converter == "path" else "seg") + f"({arg})}}")
        else:
            name_parts += [w[:1].upper() + w[1:] for w in _words(segment)]
            pieces.append(segment)
    name = method.lower() + _pascal(name_parts)
    url = "/api/" + "/".join(pieces)
    quoted = f"`{url}`" if params else f"'{url}'"
    args = ", ".join(params + ["options"])
    return name, f"  {name}: ({args}) => send('{method}', {quoted}, options),"


def render(routes: list[tuple[str, str, str]]) -> str:
    faces: dict[str, dict[str, str]] = {"home": {}, "admin": {}}
    for face, method, rule in routes:
        name, line = function(method, rule)
        made = faces.setdefault(face, {})
        if name in made and made[name] != line:
            raise ValueError(f"two {face} routes would both be called {name}")
        made[name] = line
    out = [
        "/**",
        " * One function per API route, made from the route manifest.",
        " *",
        " * Generated by tools/js_api.py. Do not edit: change the route in",
        " * ninaivu/server/ and run python tools/route_manifest.py, then",
        " * python tools/js_api.py. The hand-written fetch layer is http.js; it",
        " * is exported from here as well, so `from './api.js'` still finds it.",
        " */",
        "",
        "import { consoleJson, homeSend, withQuery } from './http.js';",
        "",
        "export * from './http.js';",
        "",
        "const seg = (value) => encodeURIComponent(String(value));",
        "const path = (value) => String(value).split('/').map(encodeURIComponent).join('/');",
        "",
    ]
    senders = {
        "home": "(method, url, options = {}) => homeSend(method, withQuery(url, options.query), options)",
        "admin": "(method, url, options = {}) => consoleJson(withQuery(url, options.query),\n"
                 "  { method, body: options.body, signal: options.signal })",
    }
    words = {"home": "The family app's routes (port 80).",
             "admin": "The console's routes (port 3000)."}
    for face in ("home", "admin"):
        out += [f"/** {words[face]} */", "export const " + face + " = (() => {",
                "  const send = " + senders[face].replace("\n", "\n  ") + ";",
                "  return {"]
        out += ["  " + faces[face][name] for name in sorted(faces[face])]
        out += ["  };", "})();", ""]
    return "\n".join(out)


def build() -> str:
    return render(parse(MANIFEST.read_text(encoding="utf-8")))


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        current = FILE.read_text(encoding="utf-8") if FILE.exists() else ""
        if current != text:
            print(f"{FILE.relative_to(ROOT)} is out of date: run python tools/js_api.py")
            return 1
        return 0
    FILE.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {FILE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
